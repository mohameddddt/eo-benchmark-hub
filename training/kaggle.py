#!/usr/bin/env python3
"""Build, push and collect the Kaggle training kernels.

    python training/kaggle.py push eurosat        # builds + pushes kernel eobench-eurosat
    python training/kaggle.py status eurosat
    python training/kaggle.py pull eurosat        # -> data/kaggle/eurosat/

Each kernel is a single script carrying the repo's `eobench_eval` and
`eobench_train` packages as an embedded zip, so a kernel always runs exactly
the code of the commit it was pushed from (no dataset-version drift).
Kernels are created private; flip them public on kaggle.com to share.
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "training" / "build"
OWNER = "mohameddddt"

KERNELS = {
    "eurosat": {
        "dataset": "nilesh789/eurosat-rgb",
        "entry": 'from eobench_train.run_classification import main\n'
                 'main("eurosat", str(find_input("nilesh789/eurosat-rgb")), None, 128)',
    },
    "resisc45": {
        "dataset": "aqibrehmanpirzada/nwpuresisc45",
        "entry": 'from eobench_train.run_classification import main\n'
                 'main("resisc45", str(find_input("aqibrehmanpirzada/nwpuresisc45")), 256, 160)',
    },
    "landcoverai": {
        "dataset": "adrianboguszewski/landcoverai",
        "entry": 'from eobench_train.segmentation import main\n'
                 'main(str(find_input("adrianboguszewski/landcoverai")))',
    },
}


def payload() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for pkg in (ROOT / "evaluation" / "eobench_eval", ROOT / "training" / "eobench_train"):
            for f in pkg.rglob("*.py"):
                z.write(f, f.relative_to(pkg.parent).as_posix())
    return base64.b64encode(buf.getvalue()).decode()


def build(bench: str) -> Path:
    k = KERNELS[bench]
    d = BUILD / bench
    d.mkdir(parents=True, exist_ok=True)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                            capture_output=True, text=True).stdout.strip()
    script = (
        f'"""EO-Bench Hub — {bench} model zoo. Auto-generated by training/kaggle.py (repo @ {commit}).\n'
        f'Source: https://github.com/{OWNER}/eo-benchmark-hub/tree/master/training"""\n'
        "import base64, io, sys, zipfile\n"
        f'PAYLOAD = "{payload()}"\n'
        'zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall("/tmp/eobench_src")\n'
        'sys.path.insert(0, "/tmp/eobench_src")\n'
        "from eobench_train.common import find_input\n"
        f"{k['entry']}\n"
    )
    (d / "run.py").write_text(script, encoding="utf-8")
    (d / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{OWNER}/eobench-{bench}",
        "title": f"eobench-{bench}",
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [k["dataset"]],
        "competition_sources": [],
        "kernel_sources": [],
    }, indent=2))
    return d


def kaggle(*args: str) -> int:
    return subprocess.call(["kaggle", *args])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["build", "push", "status", "pull"])
    ap.add_argument("bench", choices=list(KERNELS))
    a = ap.parse_args()
    ref = f"{OWNER}/eobench-{a.bench}"
    if a.action in ("build", "push"):
        d = build(a.bench)
        print(f"built {d / 'run.py'} ({(d / 'run.py').stat().st_size / 1024:.0f} KB)")
        if a.action == "push":
            sys.exit(kaggle("kernels", "push", "-p", str(d)))
    elif a.action == "status":
        sys.exit(kaggle("kernels", "status", ref))
    else:
        dest = ROOT / "data" / "kaggle" / a.bench
        dest.mkdir(parents=True, exist_ok=True)
        sys.exit(kaggle("kernels", "output", ref, "-p", str(dest), "-o"))


if __name__ == "__main__":
    main()
